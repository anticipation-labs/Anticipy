async def drive_extension_action(intent_row: dict, ctx, ext_id: str, timeout_s: int = 240) -> dict:
    """After analyze created an intent row, drive the extension to ACTUALLY
    execute it via the SW debug hook (fully local — no Supabase broadcast,
    so the user's installed extension doesn't fire too).

    Returns: { 'agent_status': {...}, 'visited_urls': [...], 'final_message': '...' }
    """
    visited = set()

    def on_request(req):
        try:
            if req.resource_type == "document":
                visited.add(req.url)
        except Exception:
            pass
    ctx.on("request", on_request)

    main_page = await ctx.new_page()
    try:
        # Land on a neutral starting URL so the agent has a tab to act on
        try:
            await main_page.goto("https://www.google.com/", timeout=20_000, wait_until="domcontentloaded")
            visited.add("https://www.google.com/")
        except Exception:
            pass
        await asyncio.sleep(1.0)

        # Find the SW + clear any stale agentStatus
        sw = None
        for s in ctx.service_workers:
            if s.url.startswith(f"chrome-extension://{ext_id}/"):
                sw = s; break
        if sw is None:
            return {"agent_status": None, "error": "no SW", "visited_urls": list(visited)}
        try:
            await sw.evaluate(
                "() => new Promise(r => chrome.storage.local.remove('agentStatus', () => r(true)))"
            )
        except Exception:
            pass

        # Build the confirmed-intent payload from the row produced by analyze.
        # We surface the user's natural-language summary as the browser_task —
        # that's what the BrowserAgent uses as the goal.
        payload = {
            **intent_row,
            "status": "confirmed",
            "parameters": {
                **(intent_row.get("parameters") or {}),
                "browser_task": (intent_row.get("parameters", {}) or {}).get("browser_task")
                                 or intent_row.get("summary_for_user", ""),
            },
        }
        try:
            await sw.evaluate(
                "(intent) => globalThis.__anticipy_debug_run_intent && globalThis.__anticipy_debug_run_intent(intent)",
                payload,
            )
        except Exception as e:
            return {"agent_status": None, "error": f"debug hook: {e}", "visited_urls": list(visited)}

        # Poll the agentStatus from the SW until terminal (done / failed)
        deadline = time.time() + timeout_s
        last_status = None
        agent_status: dict | None = None
        while time.time() < deadline:
            await asyncio.sleep(4)
            try:
                agent_status = await sw.evaluate(
                    """() => new Promise(r => chrome.storage.local.get('agentStatus', d => r(d.agentStatus || null)))"""
                )
            except Exception:
                agent_status = None
            cur = (agent_status or {}).get("status")
            if cur != last_status:
                print(f"      [t={int(time.time()-(deadline-timeout_s))}s] agentStatus={cur}", flush=True)
                last_status = cur
            if cur in ("done", "failed"):
                break

        return {
            "agent_status": agent_status,
            "final_message": (agent_status or {}).get("message", ""),
            "visited_urls": list(visited),
        }
    finally:
        try: ctx.remove_listener("request", on_request)
        except Exception: pass
        try: await main_page.close()
        except Exception: pass


async def run_scenario(scenario: dict, user_email: str, user_id: str | None, jwt: str,
                        ctx=None, ext_id: str | None = None) -> dict:
    session_id = str(uuid.uuid4())
    print(f"\n=== {scenario['name']} ===", flush=True)
    print(f"  session_id={session_id[:8]}")
    print(f"  transcript: {len(scenario['transcript'])} lines, {sum(len(l) for l in scenario['transcript'])} chars")
    print(f"  expected: {len(scenario['expected_intents'])} intents, {len(scenario['noise_should_NOT_act_on'])} noise items")

    await insert_session(session_id, user_email, user_id=user_id)
    try:
        # POST the transcript to /api/engine/analyze
        t0 = time.time()
        analyze_resp = await call_analyze(scenario["transcript"], session_id, jwt)
        analyze_t = time.time() - t0
        if "error" in analyze_resp:
            print(f"  [analyze ERROR] {analyze_resp['error']}", flush=True)
            return {"scenario": scenario, "error": analyze_resp["error"], "passed": False}

        # Wait briefly for INSERT to land (analyze does it synchronously usually)
        await asyncio.sleep(2)
        intents = await get_session_intents(session_id)
        extracted_summaries = [i.get("summary_for_user") or "" for i in intents]
        print(f"  analyze: {analyze_t:.1f}s, {len(extracted_summaries)} intents extracted")
        for s in extracted_summaries:
            print(f"    · {s[:120]}")

        judgment = await judge_extraction(
            scenario["transcript"],
            scenario["expected_intents"],
            scenario["noise_should_NOT_act_on"],
            extracted_summaries,
        )
        if "error" in judgment:
            print(f"  [judge ERROR] {judgment['error']}", flush=True)
            return {"scenario": scenario, "error": judgment["error"], "passed": False}

        score = score_scenario(scenario, intents, judgment)
        tag = "✓ PASS" if score["passed"] else "✗ FAIL"
        print(f"  voice→intent {tag}: matched={score['matched']}/{score['expected_n']} "
              f"missed={score['missed']} fp={score['false_positives_on_noise']} "
              f"spurious={score['spurious_extra']} "
              f"(p={score['precision']} r={score['recall']})")
        if not score["passed"]:
            for d in (judgment.get("details") or [])[:6]:
                print(f"    {d}")

        # ── ACTION HALF: pick the first browser-routed intent and DRIVE the
        # extension to execute it. This is the actual "press yes" step. ──
        action_result = None
        if not intents:
            # 0 intents extracted is the CORRECT outcome for pleasantries —
            # nothing to act on means the action half trivially passes.
            action_passed = True
            print(f"  intent→action ✓ PASS: no intents to act on (correct for noise-only scenarios)")
        elif ctx and ext_id:
            actionable = [i for i in intents if (i.get("action_type") or "").startswith("browser")]
            if not actionable:
                actionable = intents  # fall back: try the first one regardless of type
            target = actionable[0]
            print(f"  → driving extension on intent: {(target.get('summary_for_user') or '')[:90]}")
            try:
                action_result = await drive_extension_action(target, ctx, ext_id)
            except Exception as e:
                action_result = {"error": f"driver: {e}", "agent_status": None, "visited_urls": []}
            ag = (action_result or {}).get("agent_status") or {}
            ag_status = ag.get("status")
            ag_msg = (ag.get("message") or "")
            # Pass conditions:
            # - status="done" → agent completed
            # - status="failed" with a clean DECLINE message (task not browser-doable,
            #   needs login the agent doesn't have, etc.) → correct refusal, not a bug
            decline_signals = (
                "cannot ", "can't ", "unable to ",                    # broad
                "real-world action", "requires a real",
                "requires login", "require login", "requires logging",
                "logging into", "login required",
                "do not have the credentials", "credentials to log",
                "not signed in", "not logged in", "needs sign in",
                "sign in", "sign-in", "log in", "log-in",
                "not a browser", "out of scope", "not actionable",
                "not possible in a browser", "no clear way",
                "google account", "requires authentication",
                "communication task", "messaging task",
                "directly performed", "cannot directly",
                "cannot complete", "cannot proceed", "cannot continue",
                "cannot be done", "cannot be performed",
            )
            graceful_decline = ag_status == "failed" and any(s in ag_msg.lower() for s in decline_signals)
            action_passed = (ag_status == "done") or graceful_decline
            atag = "✓ PASS" if action_passed else "✗ FAIL"
            why = " (graceful decline)" if graceful_decline else ""
            print(f"  intent→action {atag}{why}: agentStatus={ag_status} | {ag_msg[:160]}")
        else:
            action_passed = False
            print(f"  intent→action SKIP: no ctx/ext_id")

        full_pass = score["passed"] and action_passed
        return {
            "scenario": scenario, "session_id": session_id,
            "extracted": extracted_summaries, "judgment": judgment,
            "score": score,
            "voice_intent_passed": score["passed"],
            "action_passed": action_passed,
            "passed": full_pass,
            "action_result": action_result,
        }
    finally:
        try:
            await cleanup_session(session_id)
        except Exception:
            pass


PROD_AUTH_ENDPOINT = "https://www.anticipy.ai/api/extension/auth"


async def fetch_extension_keys() -> dict:
    """Pull Groq+Gemini keys via the same prod auth endpoint the popup uses."""
    async with httpx.AsyncClient(timeout=15) as c:
        r = await c.get(
            f"{SUPABASE_URL}/rest/v1/engine_users?select=access_code&limit=1",
            headers={"apikey": SUPABASE_SERVICE, "Authorization": f"Bearer {SUPABASE_SERVICE}"},
        )
        code = r.json()[0]["access_code"]
        r = await c.post(PROD_AUTH_ENDPOINT, json={"code": code})
        return r.json()


async def launch_extension(p):
    profile = f"/tmp/e2e_voice_profile_{uuid.uuid4().hex[:8]}"
    os.makedirs(profile, exist_ok=True)
    args = [
        f"--disable-extensions-except={EXT_DIR}",
        f"--load-extension={EXT_DIR}",
        "--no-sandbox",
        "--disable-blink-features=AutomationControlled",
        "--disable-dev-shm-usage",
        "--no-first-run", "--no-default-browser-check",
    ]
    ctx = await p.chromium.launch_persistent_context(
        user_data_dir=profile, headless=False, args=args,
        viewport={"width": 1280, "height": 800},
    )
    return ctx, profile


async def wait_extension(ctx) -> str | None:
    for _ in range(30):
        for sw in ctx.service_workers:
            if sw.url.startswith("chrome-extension://"):
                return sw.url.split("/")[2]
        await asyncio.sleep(0.5)
    return None


async def seed_extension_keys(ctx, ext_id: str, keys: dict) -> None:
    p = await ctx.new_page()
    try:
        await p.goto(f"chrome-extension://{ext_id}/popup.html", timeout=15_000)
        await p.evaluate(
            """(cfg) => new Promise((res) => {
                chrome.storage.local.set({
                  apiConfig: { groqApiKey: cfg.g, geminiApiKey: cfg.gem },
                  accessAuthorized: true,
                }, () => res(true));
            })""",
            {"g": keys.get("groqApiKey", ""), "gem": keys.get("geminiApiKey", "")},
        )
    finally:
        await p.close()


async def main(n_scenarios: int = 8):
    # Use a unique test user email to avoid clashing with real users in
    # engine_users / sessions tables
    user_email = f"e2e-test-{uuid.uuid4().hex[:8]}@anticipy-test.local"
    user_pw = f"E2eTest!{uuid.uuid4().hex[:12]}"
    print(f"E2E Voice+Action test — user_email={user_email}")
    print(f"Targeting {ANTICIPY_BASE}/api/engine/analyze")

    print("\nProvisioning Supabase Auth user + signing in…", flush=True)
    try:
        jwt = await get_or_create_test_user_jwt(user_email, user_pw)
    except Exception as e:
        print(f"FAIL: auth provisioning: {e}")
        return 1
    print(f"  got JWT, len={len(jwt)}")
    user_id = await get_user_id_from_jwt(jwt)
    print(f"  user_id={user_id}")

    print(f"\nGenerating {n_scenarios} adversarial scenarios via LLM…", flush=True)
    SCENARIOS = await generate_scenarios(n_scenarios)
    if not SCENARIOS:
        print("FAIL: scenario generation produced 0 scenarios")
        return 1
    for sc in SCENARIOS:
        print(f"  {sc.get('name','?'):<40} expected={len(sc.get('expected_intents',[]))} noise={len(sc.get('noise_should_NOT_act_on',[]))}")

    # Launch Chrome with the extension loaded, seed keys, share across scenarios
    print("\nLaunching extension Chrome…", flush=True)
    ext_keys = await fetch_extension_keys()
    if not (ext_keys.get("groqApiKey") or ext_keys.get("geminiApiKey")):
        print("FAIL: prod auth returned no keys")
        return 1

    runs = []
    profile = None
    async with async_playwright() as p:
        ctx, profile = await launch_extension(p)
        try:
            ext_id = await wait_extension(ctx)
            if not ext_id:
                print("FAIL: extension did not load")
                return 1
            print(f"  extension id: {ext_id}")
            await asyncio.sleep(3)  # give registerContentScripts a moment
            await seed_extension_keys(ctx, ext_id, ext_keys)
            print("  keys seeded")

            for sc in SCENARIOS:
                try:
                    r = await run_scenario(sc, user_email, user_id, jwt, ctx=ctx, ext_id=ext_id)
                except Exception as e:
                    r = {"scenario": sc, "error": f"{type(e).__name__}: {e}", "passed": False}
                runs.append(r)
        finally:
            try: await ctx.close()
            except Exception: pass
            if profile:
                import shutil; shutil.rmtree(profile, ignore_errors=True)

    full = sum(1 for r in runs if r.get("passed"))
    voice = sum(1 for r in runs if r.get("voice_intent_passed"))
    action = sum(1 for r in runs if r.get("action_passed"))
    n = len(runs) or 1
    print("\n" + "=" * 70)
    print(f"END-TO-END (both halves): {full}/{n} ({100*full/n:.0f}%)")
    print(f"  voice→intent half:      {voice}/{n}")
    print(f"  intent→action half:     {action}/{n}")
    print("=" * 70)
    for r in runs:
        score = r.get("score") or {}
        v = "✓" if r.get("voice_intent_passed") else "✗"
        a = "✓" if r.get("action_passed") else "✗"
        if r.get("error"):
            print(f"  v{v} a{a} {r['scenario']['name']:<42} ERROR: {r['error'][:80]}")
        else:
            agent_msg = ((r.get("action_result") or {}).get("final_message") or "")[:70]
            print(f"  v{v} a{a} {r['scenario']['name']:<42} m={score.get('matched',0)}/{score.get('expected_n',0)} "
                  f"fp={score.get('false_positives_on_noise',0)} spurious={score.get('spurious_extra',0)}"
                  + (f" | action: {agent_msg!r}" if agent_msg else ""))

    out = Path("/tmp/e2e_voice_action_detail.json")
    out.write_text(json.dumps([{
        "name": r["scenario"]["name"],
        "passed": r.get("passed", False),
        "voice_intent_passed": r.get("voice_intent_passed", False),
        "action_passed": r.get("action_passed", False),
        "error": r.get("error"),
        "extracted": r.get("extracted", []),
        "score": r.get("score", {}),
        "judgment_details": (r.get("judgment") or {}).get("details", []),
        "action_message": (r.get("action_result") or {}).get("final_message", ""),
    } for r in runs], indent=2))
    print(f"\nDetail: {out}")
    return 0 if p == len(runs) else 1


if __name__ == "__main__":
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 8
    raise SystemExit(asyncio.run(main(n_scenarios=n)))
