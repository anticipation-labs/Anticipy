"""
End-to-end voice + action test, adversarial.

Flow tested:
  long realistic transcript → /api/engine/analyze → intents in
  anticipy_intents → confirm via /api/engine/confirm → extension's
  BrowserAgent executes → status PATCHed back.

Hard scenarios:
- Long, noisy conversations with embedded intents
- Conditional intents ("if X, then Y")
- Pronouns / referential ("yeah, do that")
- Contradictions and retractions ("book Friday" "actually never mind")
- Pleasantries that should NOT trigger actions
- Multiple speakers
- Day-to-day reality (not search-Wikipedia-for-cats)

Pass criterion:
- Proactive layer extracts the right intents and skips the noise
  (precision + recall judged by Gemini against an explicit ground-truth
  list embedded in each scenario)
- For each truly-actionable intent, the extension can in fact execute it
  in the browser (action half)

Run:
    cd engine && DISPLAY=:99 python test_e2e_voice_action.py
"""

