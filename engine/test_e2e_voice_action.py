# ---------------------------------------------------------------------------
# Scenarios are generated by an LLM at runtime — no hand-coded transcripts,
# no pre-programming. The generator returns realistic conversations between
# the wearer and one or more other people, with mixed signal/noise/edge
# cases (retractions, conditionals, pronouns, delegations, pleasantries,
# ambient sound). It also returns the EXPECTED actionable intents and the
# NOISE items that should NOT be acted on, which the judge later scores
# against what /api/engine/analyze actually extracted.
# ---------------------------------------------------------------------------


GENERATOR_SYSTEM = """You generate ONE adversarial test for a proactive intent-extraction system.

Output: ONE JSON object. The conversation must be REALISTIC day-to-day speech, \
not stilted. Mix in challenging patterns:

- delegations to other people (the wearer telling Sarah/John to do something — those are NOT the wearer's-assistant tasks)
- retractions (intent stated then taken back in the same convo)
- conditionals (\"if X happens, then Y\") that may or may not become real intents
- pronouns / referential mentions (\"yeah do that\")
- pleasantries that look intent-shaped but aren't (\"we should grab lunch sometime\")
- ambient or off-topic chatter the system must ignore
- multiple speakers, sometimes long

JSON shape:
{
  \"name\": \"<short scenario id, snake_case>\",
  \"transcript\": [\"Wearer: ...\", \"Friend: ...\", ...],
  \"expected_intents\": [\"<one-line intent>\", ...],
  \"noise_should_NOT_act_on\": [\"<short description>\", ...]
}

Distribution: at least 5 different scenario shapes — long meeting, casual chatter, all-noise, conditional+retraction, ambient with buried intent. Each transcript should have between 0 and 5 expected_intents (zero is a valid difficulty level — the system must not invent intents).
"""

GENERATOR_USER = (
    "Generate one scenario, biased toward the difficulty pattern: {pattern}. "
    "Be creative; don't reuse phrasing from prior generations."
)

DIFFICULTY_PATTERNS = [
    "morning chatter with 2-3 buried action items",
    "long workday meeting with multiple delegations + 2-3 wearer actions",
    "casual conversation with zero real actions (pleasantries only)",
    "retraction in mid-conversation: state then reverse one or two intents",
    "ambient/cafe noise with exactly one intent buried in unrelated talk",
    "conditional intents tied to weather or time-of-day, with retractions",
    "evening run-down with end-of-day errand list (3-5 actions)",
    "phone call where wearer is half listening, occasional intents drop in",
]


async def _gemini_json(system: str, user: str, max_tokens: int = 4096, temperature: float = 0.9) -> dict:
    body = {
        "system_instruction": {"parts": [{"text": system}]},
        "contents": [{"role": "user", "parts": [{"text": user}]}],
        "generationConfig": {
            "temperature": temperature,
            "maxOutputTokens": max_tokens,
            "responseMimeType": "application/json",
        },
    }
    async with httpx.AsyncClient(timeout=120) as c:
        r = await c.post(f"{GEMINI_URL}?key={GEMINI_KEY}", json=body)
        r.raise_for_status()
        txt = r.json()["candidates"][0]["content"]["parts"][0]["text"]
        return json.loads(txt)


async def generate_scenarios(n: int) -> list[dict]:
    out = []
    for i in range(n):
        pattern = DIFFICULTY_PATTERNS[i % len(DIFFICULTY_PATTERNS)]
        try:
            sc = await _gemini_json(GENERATOR_SYSTEM, GENERATOR_USER.format(pattern=pattern))
            sc["name"] = sc.get("name") or f"scenario_{i}"
            out.append(sc)
        except Exception as e:
            print(f"  [gen failed for pattern {pattern}: {e}]", flush=True)
    return out


