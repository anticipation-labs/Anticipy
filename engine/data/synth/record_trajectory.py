# ─── Recipe contract ──────────────────────────────────────────────────


@dataclass
class RecipeAction:
    """One step in a recipe. The recorder captures a screenshot BEFORE
    executing this action, then dispatches the action via CDP.

    The action dict matches Fara's tool_call schema: {"action": "left_click",
    "coordinate": [x, y]} or {"action": "type", "text": "..."} etc.
    """
    action: dict
    intent_hint: str = ""  # short human description, used to seed COT


@dataclass
class Recipe:
    scenario: str  # e.g. "gmail_compose"
    goal: str
    actions: list[RecipeAction]
    setup_url: Optional[str] = None  # initial nav before first action
    verifier: Optional[Callable[[CDPSession], bool]] = None

    def task_id(self, run_index: int) -> str:
        return f"anticipy_{self.scenario}_{run_index:03d}"


# ─── Chain-of-thought narration ──────────────────────────────────────


def _narrate_via_cascade(goal: str, intent_hint: str, prev_actions: list[dict]) -> str:
    """Ask Mistral for a one-line chain-of-thought given the goal,
    the intent hint for this step, and the prior actions. Cheap,
    cascade-routed, falls back to the intent hint if cascade is down.
    """
    api_key = os.environ.get("MISTRAL_API_KEY")
    if not api_key:
        return intent_hint or "next action"
    try:
        prev_summary = ", ".join(
            f"{a.get('action','?')}({a.get('coordinate', a.get('text', a.get('url', '')))})"
            for a in prev_actions[-5:]
        )
        msg = (
            f"Goal: {goal}\n"
            f"Recent actions: {prev_summary or '(none yet)'}\n"
            f"This step's intent: {intent_hint}\n\n"
            "Respond with ONE first-person sentence (<=22 words) explaining why "
            "this action comes next. No prose around it. No quotes."
        )
        r = httpx.post(
            "https://api.mistral.ai/v1/chat/completions",
            json={
                "model": "mistral-small-latest",
                "messages": [
                    {"role": "system", "content": "You are a GUI agent narrating a single step."},
                    {"role": "user", "content": msg},
                ],
                "temperature": 0.3,
                "max_tokens": 60,
            },
            headers={"Authorization": f"Bearer {api_key}"},
            timeout=10.0,
        )
        r.raise_for_status()
        data = r.json()
        text = (data["choices"][0]["message"]["content"] or "").strip()
        return text or (intent_hint or "next action")
    except Exception as e:
        _logger.warning("narration cascade failed (%s); using intent_hint", e)
        return intent_hint or "next action"


# ─── Recorder ─────────────────────────────────────────────────────────


def record_recipe(
    recipe: Recipe,
    run_index: int,
    out_dir: Path = TRAJECTORIES_DIR,
    seed: Optional[int] = None,
    skip_narration: bool = False,
) -> dict:
    """Run one recipe playthrough and write a trajectory JSONL row.

    Returns the trajectory dict. The screenshot files land in
    out_dir / <scenario> / <task_id> /step_NNN.png and the JSONL row
    appends to out_dir / <scenario>.jsonl.
    """
    task_id = recipe.task_id(run_index)
    scenario_dir = out_dir / recipe.scenario / task_id
    scenario_dir.mkdir(parents=True, exist_ok=True)

    sess = connect_to_chrome(open_url=recipe.setup_url or "about:blank", seed=seed)
    steps_out: list[dict] = []
    prior_actions: list[dict] = []
    completion_status = "success"
    try:
        if recipe.setup_url:
            try:
                navigate(sess, recipe.setup_url, wait_for_load_s=20.0)
            except Exception as e:
                _logger.error("setup navigate failed: %s", e)
                completion_status = "failed"

        for i, ra in enumerate(recipe.actions):
            wait_for_settle(sess, timeout_s=2.0)
            shot = capture_screenshot(sess)
            shot_path = scenario_dir / f"step_{i:03d}.png"
            shot_path.write_bytes(shot)

            cot = (
                ra.intent_hint
                if skip_narration
                else _narrate_via_cascade(recipe.goal, ra.intent_hint, prior_actions)
            )

            step = {
                "step_index": i,
                "screenshot": str(shot_path.relative_to(out_dir.parent.parent)),
                "history_so_far": prior_actions[-5:],  # last 5
                "chain_of_thought": cot,
                "action": ra.action,
            }
            steps_out.append(step)

            # Dispatch the action via CDP. Wrap fara-style.
            res = dispatch_fara_action(sess, {**ra.action, "refusal": False})
            if not res.get("ok"):
                _logger.warning("step %d dispatch failed: %s", i, res)
                completion_status = "failed"
                break

            prior_actions.append(ra.action)

        if recipe.verifier and completion_status == "success":
            try:
                ok = recipe.verifier(sess)
                if not ok:
                    completion_status = "failed"
            except Exception as e:
                _logger.error("verifier threw: %s", e)
                completion_status = "failed"

    finally:
        sess.close()

    trajectory = {
        "task_id": task_id,
        "scenario": recipe.scenario,
        "goal": recipe.goal,
        "steps": steps_out,
        "completion_status": completion_status,
        "recorded_at": time.time(),
    }
    jsonl_path = out_dir / f"{recipe.scenario}.jsonl"
    with jsonl_path.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(trajectory) + "\n")
    return trajectory


def validate_trajectory_dir(scenario_jsonl: Path) -> dict:
    """Schema-validate every row in scenario_jsonl. Confirm referenced
    screenshot files exist and decode as PNG.
    """
    from PIL import Image
    out = {"file": str(scenario_jsonl), "rows": 0, "errors": [], "screenshots_ok": 0, "screenshots_missing": 0}
    if not scenario_jsonl.exists():
        out["errors"].append("file_not_found")
        return out
    with scenario_jsonl.open() as fh:
        for line_no, line in enumerate(fh, 1):
            line = line.strip()
            if not line:
                continue
            out["rows"] += 1
            try:
                row = json.loads(line)
            except Exception as e:
                out["errors"].append(f"line {line_no}: bad json: {e}")
                continue
            for required in ("task_id", "goal", "steps", "completion_status"):
                if required not in row:
                    out["errors"].append(f"line {line_no}: missing field {required}")
            for step in row.get("steps", []):
                shot_rel = step.get("screenshot")
                if not shot_rel:
                    continue
                shot_path = scenario_jsonl.parent.parent.parent / shot_rel
                if not shot_path.exists():
                    out["screenshots_missing"] += 1
                    continue
                try:
                    Image.open(str(shot_path)).verify()
                    out["screenshots_ok"] += 1
                except Exception as e:
                    out["errors"].append(f"screenshot decode failed: {shot_path}: {e}")
    return out


