"""Phase fara-4 trajectory recorder.

Drives a "recipe" (a deterministic playthrough of a real task on real
Chrome) and emits a Fara-format trajectory JSONL row. Each step
captures a screenshot before the action, generates a chain-of-thought
narration via the cascade (Mistral on OpenRouter, cheap), and records
the action in Fara's native format.

The output JSONL row matches Fara training data format:

    {
      "task_id": "anticipy_<scenario>_<n>",
      "goal": "<task goal text>",
      "steps": [
        {
          "step_index": 0,
          "screenshot": "trajectories/<scenario>/<task_id>/step_000.png",
          "history_so_far": [],
          "chain_of_thought": "<narration of why this action is next>",
          "action": {"action": "left_click", "coordinate": [x,y]}
        },
        ...
      ],
      "completion_status": "success" | "failed"
    }

Recipes are deterministic Python classes with .setup(sess), .steps(),
and .verify() methods. The recorder loops the recipe's steps, captures
screenshots, narrates, and records.

Per Rule 1 (no API for any service): recipes navigate real UIs via
the CDP dispatcher. They do not call APIs.

Per Rule 2 (no fabrication): screenshots ARE the screen at the moment.
Chain-of-thought is generated by Mistral but the action and the screen
are real.
"""

