def build():
    held_out = {7, 12, 18, 23, 29, 34, 37, 43, 46, 49}
    people = []
    for number, case in enumerate(CASES, 1):
        name, occupation, city, zone, task, evidence, outcome, challenge = case
        ref = f"auditperson{number:04d}"
        assert len(ref) == 15
        contacts = [
            {"id": f"{ref}-contact-1", "name": "Alex Kim", "relationship": "project contact",
             "email": f"alex-{number:02d}@contacts.invalid", "phone": f"+1202555{149 + number:04d}"},
            {"id": f"{ref}-contact-2", "name": "Sam Reed", "relationship": "personal contact",
             "email": f"sam-{number:02d}@contacts.invalid"},
        ]
        # Fixture relationships are explicit records, never inferred from the
        # person's task by a runtime name/word classifier.
        if number == 1:
            contacts.append({"id": f"{ref}-contact-3", "name": "Alex Reed", "relationship": "climbing partner",
                             "email": "alex-reed-01@contacts.invalid"})
            contacts[0]["relationship"] = "client for the revised site brief"
        if number == 2:
            contacts[1]["relationship"] = "sister"
        if number == 10:
            contacts[0]["relationship"] = "client, account North, open renewal"
            contacts[1].update(name="Alex Reed", relationship="client, account South, open renewal")
        if number == 35:
            contacts[0].update(name="Sam Kim", relationship="sports-club contact")
            contacts[0].pop("phone", None)
        if number == 43:
            contacts[0]["relationship"] = "colleague who promised to send the deck"
        people.append({
            "id": ref, "fictional": True, "name": name, "occupation": occupation,
            "email": f"person-{number:02d}@anticipy-test.invalid", "phone": f"+1202555{99 + number:04d}",
            "city": city, "timezone": zone, "contacts": contacts,
            "split": "held_out" if number in held_out else "development",
            "history": [
                {"session": 1, "source": "typed", "speaker": "owner",
                 "text": f"My name is {name}. I work as a {occupation} and I live in {city}."},
                {"session": 2, "source": "fixture_evidence", "text": evidence},
            ],
            "transcript": {"source": "typed", "speaker": "owner", "text": task},
            "evaluator_only": {"required_outcome": outcome, "challenge": challenge,
                               "forbidden_live_side_effects": True},
        })
    assert len(people) == 50 and len({p["id"] for p in people}) == 50
    return people


